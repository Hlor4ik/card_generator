def build_user_message(product: ProductInput, missing: list[str]) -> str:
    """Сформировать пользовательское сообщение с данными и явной пометкой пробелов."""
    payload = {
        "name": product.name,
        "manufacturer": product.manufacturer or None,
        "specs": product.specs or {},
        "description": product.description or None,
    }
    lines = [
        "Данные о приборе (единственный источник фактов):",
        json.dumps(payload, ensure_ascii=False, indent=2),
    ]
    if missing:
        lines += [
            "",
            "Отсутствуют поля: " + ", ".join(missing) + ".",
            "Не придумывай их значения. В тексте не упоминай отсутствующие характеристики.",
        ]
    return "\n".join(lines)


def build_retry_feedback(problems: list[str]) -> str:
    """Сообщение для корректирующей попытки, если ответ не прошёл проверки длины."""
    return (
        "Предыдущий ответ нарушил ограничения:\n- "
        + "\n- ".join(problems)
        + "\nИсправь и верни снова строго JSON по той же схеме. "
        "Не добавляй и не выдумывай характеристики."
    )
